"""Расширение вопроса для поиска: бытовые слова → язык кодексов.

Прогон 72 вопросов обычных людей (10.09.2026) показал слабое место поиска:
«Как открыть ИП?» находил статьи УПК про «открытие», «закрыть ИП» — главу ГК о
займе. В кодексах нет слов «ИП», «ТОО», «декрет», «больничный», а эмбеддинг
короткого вопроса цепляется за случайное слово. Дешёвая модель переводит вопрос
в два-три запроса теми словами, которыми названы статьи, — и заодно переводит
казахский или английский вопрос на русский: корпус на русском.
"""

from typing import List

from config import Config
from docengine.generate import extract_json

PROMPT = (
    'Ты помогаешь поисковой системе по кодексам и законам Республики Казахстан. '
    'Человек задаёт вопрос бытовым языком. Верни JSON вида {"queries": ["…", "…"]} — '
    'два-три коротких поисковых запроса (5–12 слов) на русском языке в терминологии '
    'казахстанского законодательства. Раскрывай сокращения (ИП и казахское ЖК/жеке кәсіпкер → '
    'индивидуальный предприниматель, ТОО и казахское ЖШС → товарищество с ограниченной '
    'ответственностью, ЕНПФ/БЖЗҚ → единый накопительный пенсионный фонд, ЦОН → центр '
    'обслуживания населения), заменяй бытовые слова юридическими (декрет → отпуск по '
    'беременности и родам, больничный → социальное пособие по временной нетрудоспособности, '
    'уволили → расторжение трудового договора по инициативе работодателя) и формулируй так, '
    'как называются статьи кодексов: «государственная регистрация индивидуального '
    'предпринимателя», «продолжительность оплачиваемого ежегодного трудового отпуска». '
    'Вопрос на казахском или английском переведи на русский. Только JSON, без пояснений.'
)


def expand_query(question: str, provider, max_queries: int = 3) -> List[str]:
    """Запросы юридическим языком к вопросу человека; пусто — если модель не помогла.

    Ошибка модели или мусор в ответе не должны ломать чат: поиск тогда идёт
    только по исходному вопросу, как раньше.
    """
    try:
        resp = provider.chat_completion(
            messages=[{'role': 'system', 'content': PROMPT}, {'role': 'user', 'content': question}],
            model=Config.LLM_MODEL, temperature=0.0, max_tokens=200,
        )
        data = extract_json((resp or {}).get('content', ''))
    except Exception:  # noqa: BLE001 — любая беда с моделью = без расширения
        return []
    raw = data.get('queries') if isinstance(data, dict) else None
    if not isinstance(raw, list):
        return []
    out: List[str] = []
    for q in raw:
        if not isinstance(q, str) or not q.strip():
            continue
        q = q.strip()
        if q.lower() == question.strip().lower() or q in out:
            continue
        out.append(q)
    return out[:max_queries]
