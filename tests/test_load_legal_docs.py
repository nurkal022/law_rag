"""
Разбивка кодекса на статьи при загрузке корпуса.

На проде не оказалось статьи 88 ТК («двадцать четыре календарных дня») и ещё
сорока статей Трудового кодекса, пятой части статей КоАП, ГПК, ПК. Все они —
короткие статьи из одного абзаца без нумерованных пунктов: склейка строк
приклеивала тело статьи к строке заголовка, тело оставалось пустым, и статья
отбрасывалась как «короче тридцати знаков».
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from scripts.load_legal_docs import clean_text, split_by_articles  # noqa: E402

RAW = (
    'Глава 7. ВРЕМЯ ОТДЫХА\n'
    'Статья 87. Виды отпусков\n'
    '1. Работникам предоставляются следующие виды отпусков:\n'
    '1) оплачиваемые ежегодные трудовые отпуска;\n'
    '2) социальные отпуска.\n'
    '2. Оплачиваемый ежегодный трудовой отпуск предназначен для отдыха работника, восстановления\n'
    'работоспособности и предоставляется с сохранением места работы и средней заработной платы.\n'
    'Сноска. Статья 87 с изменениями, внесенными Законом РК от 07.07.2020 № 361-VI\n'
    '(вводится в действие по истечении десяти календарных дней после дня его первого\n'
    'официального опубликования).\n'
    'Статья 88. Продолжительность основного оплачиваемого ежегодного трудового\n'
    'отпуска\n'
    'Основной оплачиваемый ежегодный трудовой отпуск работникам предоставляется\n'
    'продолжительностью двадцать четыре календарных дня, если большее количество дней\n'
    'не предусмотрено настоящим Кодексом.\n'
    'Статья 89. Дополнительные оплачиваемые ежегодные трудовые отпуска\n'
    '1. Дополнительные оплачиваемые ежегодные трудовые отпуска предоставляются:\n'
    '1) работникам, занятым на тяжелых работах, продолжительностью не менее шести календарных дней.\n'
)


def test_single_paragraph_article_survives_the_split():
    chunks = split_by_articles(clean_text(RAW), 'Глава')
    titles = [c['title'][:10] for c in chunks]
    assert titles == ['Статья 87.', 'Статья 88.', 'Статья 89.']
    art88 = chunks[1]['content']
    assert 'двадцать четыре календарных дня' in art88
    assert art88.startswith('Глава 7. ВРЕМЯ ОТДЫХА')


def test_article_with_points_keeps_its_body_and_section():
    chunks = split_by_articles(clean_text(RAW), 'Глава')
    art87 = chunks[0]['content']
    assert '1) оплачиваемые ежегодные трудовые отпуска' in art87
    assert 'Сноска. Статья 87' in art87
    assert chunks[0]['section'] == 'Глава 7. ВРЕМЯ ОТДЫХА'


def test_stray_short_fragment_without_a_title_is_still_dropped():
    chunks = split_by_articles(clean_text('Глава 1. Общие положения\nкороткий хвост\n'), 'Глава')
    assert chunks == []
