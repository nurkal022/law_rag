/**
 * Сокращение акта по названию документа в корпусе: «Гражданский кодекс РК
 * (Общая часть)» → «ГК РК». Интерфейс получает от сервера название целиком,
 * а чип ссылки должен быть коротким. Неизвестное название возвращается как есть.
 */
const TITLE_TO_ACT: [RegExp, string][] = [
  [/^Конституция/i, 'Конституция РК'],
  [/^Гражданский процессуальный/i, 'ГПК РК'],
  [/^Гражданский кодекс/i, 'ГК РК'],
  [/^Уголовно-процессуальный/i, 'УПК РК'],
  [/^Уголовный/i, 'УК РК'],
  [/^Трудовой/i, 'ТК РК'],
  [/^Налоговый/i, 'НК РК'],
  [/^Бюджетный/i, 'БК РК'],
  [/^Земельный/i, 'ЗК РК'],
  [/^Предпринимательский/i, 'ПК РК'],
  [/^Экологический/i, 'ЭК РК'],
  [/^Административный процедурно/i, 'АППК РК'],
  [/административных правонарушениях/i, 'КоАП РК'],
  [/О браке/i, 'КоБС РК'],
  [/О нормативных правовых актах/i, 'ЗРК О НПА'],
  [/О правовых актах/i, 'ЗРК О ПА'],
  [/госзакупках|государственных закупках/i, 'ЗРК О госзакупках'],
  [/Конституционном Суде/i, 'КЗРК О КС'],
  [/О прокуратуре/i, 'КЗРК О прокуратуре'],
  [/судебной системе/i, 'КЗРК О судебной системе'],
]

export function actCode(title: string): string {
  for (const [re, code] of TITLE_TO_ACT) if (re.test(title)) return code
  return title
}

/** «ГК РК 178» из названия документа корпуса и номера статьи; без статьи — только акт. */
export function normCode(title: string, article?: string | null): string {
  const act = actCode(title)
  return article ? `${act} ${article}` : act
}

/**
 * «ГК РК 297» + kz → «ҚР АК 297». Номер статьи не трогаем: он одинаков
 * во всех редакциях. Незнакомый акт возвращается как есть.
 */
export function citeCode(code: string, lang: Lang): string {
  if (lang === 'ru') return code
  for (const act of ACTS) {
    if (code === act.ru) return act[lang]
    if (code.startsWith(act.ru + ' ')) return `${act[lang]} ${code.slice(act.ru.length + 1)}`
  }
  return code
}
